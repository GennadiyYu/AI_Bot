export function buildUserPrompt({
  question,
  retrievedContext = [],
  recentHistory = [],
}) {
  const historyBlock = recentHistory.length
    ? recentHistory
        .map((item) => `${item.role === "assistant" ? "Ассистент" : "Пользователь"}: ${item.content}`)
        .join("\n")
    : "История отсутствует.";

  const contextBlock = normalizeRetrievedContext(retrievedContext);

  return [
    `Вопрос пользователя: ${question}`,
    ``,
    `Недавняя история диалога:`,
    historyBlock,
    ``,
    `Контекст из документов:`,
    contextBlock || "Контекст отсутствует.",
    ``,
    `Нужно ответить как сильный ассистент руководителя digital-агентства: по делу, структурно и с акцентом на практическую пользу.`,
  ].join("\n");
}

export function resolveSystemPrompt({ question = "", retrievedContext = [], fileNames = [] }) {
  const profile = detectAnalysisProfile({ question, retrievedContext, fileNames });

  switch (profile.type) {
    case "mediaplan":
      return MEDIAPLAN_ANALYST_PROMPT;
    case "report":
      return REPORT_ANALYST_PROMPT;
    case "commercial":
      return COMMERCIAL_PROPOSAL_PROMPT;
    case "brief":
      return BRIEF_ANALYST_PROMPT;
    case "contract":
      return CONTRACT_ANALYST_PROMPT;
    default:
      return EXEC_ASSISTANT_PROMPT;
  }
}

export function detectAnalysisProfile({ question = "", retrievedContext = [], fileNames = [] }) {
  const text = [
    question,
    ...fileNames,
    ...extractTextValues(retrievedContext),
  ]
    .join(" ")
    .toLowerCase();

  const rules = [
    {
      type: "mediaplan",
      keywords: [
        "медиаплан",
        "медиа план",
        "budget",
        "бюджет",
        "канал",
        "каналы",
        "размещение",
        "cpm",
        "cpc",
        "cpa",
        "cpl",
        "ctr",
        "romi",
        "охват",
        "показы",
        "клики",
        "лиды",
        "performance",
        "traffic",
      ],
    },
    {
      type: "report",
      keywords: [
        "отчёт",
        "отчет",
        "report",
        "результаты",
        "динамика",
        "факт",
        "план-факт",
        "аналитика",
        "конверсия",
        "выручка",
        "эффективность",
        "kpi",
        "итоги",
      ],
    },
    {
      type: "commercial",
      keywords: [
        "коммерческое предложение",
        "кп",
        "proposal",
        "offe",
        "оффер",
        "scope",
        "смета",
        "стоимость",
        "стоимост",
        "стоимость работ",
        "предложение клиенту",
      ],
    },
    {
      type: "brief",
      keywords: [
        "бриф",
        "brief",
        "цели проекта",
        "целевая аудитория",
        "аудитория",
        "задачи проекта",
        "инсайт",
        "позиционирование",
        "requirements",
      ],
    },
    {
      type: "contract",
      keywords: [
        "договор",
        "contract",
        "соглашение",
        "штраф",
        "ответственность",
        "оплата",
        "приёмка",
        "приемка",
        "конфиденциальность",
        "интеллектуальные права",
        "форс-мажор",
      ],
    },
  ];

  let bestMatch = { type: "generic", score: 0 };

  for (const rule of rules) {
    const score = rule.keywords.reduce((sum, keyword) => {
      return sum + (text.includes(keyword) ? 1 : 0);
    }, 0);

    if (score > bestMatch.score) {
      bestMatch = { type: rule.type, score };
    }
  }

  return bestMatch;
}

function normalizeRetrievedContext(retrievedContext) {
  if (!retrievedContext || !retrievedContext.length) return "";

  return retrievedContext
    .map((item, index) => {
      if (typeof item === "string") {
        return `[Фрагмент ${index + 1}]\n${item}`;
      }

      if (item?.text) {
        const filePart = item.fileName ? `Файл: ${item.fileName}\n` : "";
        return `[Фрагмент ${index + 1}]\n${filePart}${item.text}`;
      }

      return `[Фрагмент ${index + 1}]\n${JSON.stringify(item)}`;
    })
    .join("\n\n");
}

function extractTextValues(retrievedContext) {
  if (!retrievedContext || !retrievedContext.length) return [];

  return retrievedContext.map((item) => {
    if (typeof item === "string") return item;
    if (item?.text) return item.text;
    return "";
  });
}
